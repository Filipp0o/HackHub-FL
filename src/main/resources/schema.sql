CREATE TABLE IF NOT EXISTS segnalazione (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            partecipazione_id BIGINT NOT NULL REFERENCES partecipazione(id),
    mentore_id BIGINT NOT NULL REFERENCES utente(id),
    descrizione CLOB NOT NULL,
    data_ora_creazione TIMESTAMP(9) NOT NULL,
    stato VARCHAR(32) NOT NULL,
    esito VARCHAR(32),
    motivazione CLOB,
    data_ora_esame TIMESTAMP(9),
    esaminatore_id BIGINT REFERENCES utente(id),
    CONSTRAINT ck_segnalazione_decisione CHECK (
(
                                                   stato = 'DA_ESAMINARE'
                                                   AND esito IS NULL
                                                   AND motivazione IS NULL
                                                   AND data_ora_esame IS NULL
                                                   AND esaminatore_id IS NULL
)
    OR
(
    stato = 'ESAMINATA'
    AND esito IS NOT NULL
    AND esito IN (
    'ARCHIVIATA',
    'VIOLAZIONE_CONFERMATA',
    'VIOLAZIONE_CON_ESCLUSIONE'
                 )
    AND motivazione IS NOT NULL
    AND LENGTH(TRIM(motivazione)) > 0
    AND data_ora_esame IS NOT NULL
    AND esaminatore_id IS NOT NULL
    )
    )
    );

CREATE TABLE IF NOT EXISTS notifica_segnalazione (
                                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     segnalazione_id BIGINT NOT NULL UNIQUE REFERENCES segnalazione(id),
    destinatario_id BIGINT NOT NULL REFERENCES utente(id),
    data_ora_creazione TIMESTAMP(9) NOT NULL,
    letta BOOLEAN NOT NULL DEFAULT FALSE
    );