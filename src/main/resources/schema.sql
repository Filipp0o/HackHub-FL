CREATE TABLE IF NOT EXISTS sottomissione (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             partecipazione_id BIGINT NOT NULL UNIQUE,
                                             contenuto CLOB NOT NULL,
                                             CONSTRAINT fk_sottomissione_partecipazione
                                             FOREIGN KEY (partecipazione_id) REFERENCES partecipazione(id)
    );

CREATE TABLE IF NOT EXISTS valutazione (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           sottomissione_id BIGINT NOT NULL UNIQUE,
                                           giudice_id BIGINT NOT NULL,
                                           giudizio CLOB NOT NULL,
                                           punteggio DECFLOAT NOT NULL,
                                           data_ora TIMESTAMP(9) NOT NULL,
    CONSTRAINT ck_valutazione_punteggio
    CHECK (punteggio >= 0 AND punteggio <= 10),
    CONSTRAINT fk_valutazione_sottomissione
    FOREIGN KEY (sottomissione_id) REFERENCES sottomissione(id),
    CONSTRAINT fk_valutazione_giudice
    FOREIGN KEY (giudice_id) REFERENCES utente(id)
    );

CREATE TABLE IF NOT EXISTS riscossione_premio (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  hackathon_id BIGINT NOT NULL UNIQUE,
                                                  stato VARCHAR(32) NOT NULL,
    beneficiary_ref VARCHAR,
    payment_ref VARCHAR,
    CONSTRAINT fk_riscossione_hackathon
    FOREIGN KEY (hackathon_id) REFERENCES hackathon(id),
    CONSTRAINT ck_riscossione_stato CHECK (
(
                                              stato = 'DA_CONFIGURARE'
                                              AND beneficiary_ref IS NULL
                                              AND payment_ref IS NULL
)
    OR (
           stato = 'PRONTA'
           AND beneficiary_ref IS NOT NULL
           AND LENGTH(TRIM(beneficiary_ref)) > 0
    AND payment_ref IS NULL
    )
    OR (
           stato = 'EROGATA'
           AND beneficiary_ref IS NOT NULL
           AND LENGTH(TRIM(beneficiary_ref)) > 0
    AND payment_ref IS NOT NULL
    AND LENGTH(TRIM(payment_ref)) > 0
    )
    )
    );

